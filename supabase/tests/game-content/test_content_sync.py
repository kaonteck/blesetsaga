from playwright.sync_api import sync_playwright
import os; SP=os.path.dirname(os.path.abspath(__file__)); OUT=os.environ.get('SHOTS','/tmp')
MOCK=open(SP+'/mock-supabase.js').read();res=[]
def ok(c,l):res.append(('OK  ' if c else 'FAIL')+' '+l)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page();errs=[]
    pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and 'ERR_FAILED' not in m.text and errs.append(m.text))
    pg.route('**/supabase-js@*/**',lambda r:r.fulfill(body=MOCK,content_type='application/javascript'))
    pg.route('**/fonts.g*/**',lambda r:r.abort())
    pg.goto('http://localhost:8765/');pg.wait_for_function('typeof S!=="undefined"&&S&&S.data&&S.data._srv',timeout=20000)
    g=lambda js:pg.evaluate(js)
    base_hp=g("S.data._srv.monster.forest.base.hp")   # 서버 값을 덮기 전 게임의 값 (게임 밸런스가 바뀌어도 테스트가 맞게)
    ok(isinstance(base_hp,(int,float)) and base_hp!=777,f'덮기 전 원래 값 보관 (hp {base_hp})')
    ok(g("monster('forest').hp")==777,'공개된 몬스터 값 적용 (hp 777)')
    ok(g("monster('forest').rev")==3,'몬스터 변경 횟수 = 서버 rev')
    ok(g("monster('st_hound').hp")!=1,'비공개 항목은 적용 안 함')
    ok(g("quest('S1').title")!='미래 퀘스트','예약(미래) 항목은 아직 적용 안 함')
    ok(g("ITEMS.potion.name")=='서버 회복약','아이템 이름 적용')
    ok(g("cfg().levelCap")==50 and g("cfg().expBase")==100,'설정은 일부만 덮기 (levelCap 50, expBase 유지)')
    ok(g("S.data.notices.some(n=>n.id==='n_srv')"),'서버 공지 추가')
    ok(g("activeEvents().some(e=>e.id==='srv:ev1'&&e.title==='서버 보스 출현')"),'전광판 이벤트 표시')
    # 실시간: forest 삭제, potion 이름 변경
    g("window.__CT=window.__CT.filter(r=>r.id!=='forest');window.__CT.find(r=>r.id==='potion').data.name='바뀐 회복약';window.__CT_CB({eventType:'UPDATE'})")
    pg.wait_for_timeout(1500)
    ok(g("monster('forest').hp")==base_hp,f'서버에서 지우면 원래 값(hp {base_hp})으로')
    ok(g("ITEMS.potion.name")=='바뀐 회복약','실시간 변경 반영')
    ok(not g("!!(S.data._srv.monster||{}).forest"),'지운 항목 표시 정리')
    # 이벤트 기간 종료 → 사라짐
    g("window.__CT=window.__CT.filter(r=>r.kind!=='event');window.__CT_CB({})");pg.wait_for_timeout(1300)
    ok(not g("activeEvents().some(e=>e.id==='srv:ev1')"),'서버 이벤트 내리면 전광판에서 사라짐')
    # 세이브에 표시가 남는지 → 새로고침 후 서버에서 potion 삭제 → 원래 이름 복귀
    pg.wait_for_timeout(500);saved=g("JSON.parse(localStorage.getItem(SAVE)).data._srv.item.potion.base.name")
    ok(saved=='회복약','세이브에 원래 값 저장 (회복약)')
    pg.add_init_script("window.__AFTER_RELOAD=1")
    pg.reload();pg.wait_for_function('typeof S!=="undefined"&&S&&S.data&&S.data._srv',timeout=20000);pg.wait_for_timeout(800)
    ok(g("ITEMS.potion.name")=='서버 회복약','새로고침 후 서버 값 다시 적용')
    g("window.__CT=window.__CT.filter(r=>r.id!=='potion');window.__CT_CB({})");pg.wait_for_timeout(1300)
    ok(g("ITEMS.potion.name")=='회복약','새로고침 뒤에도 지우면 원래 이름 복귀')
    # 같은 내용이면 다시 그리지 않음(불필요한 저장 없음)
    n=g("window.__FETCHES");g("window.__CT_CB({});window.__CT_CB({});window.__CT_CB({})");pg.wait_for_timeout(1300)
    ok(g("window.__FETCHES")==n+1,'실시간 신호 여러 번 → 한 번만 다시 받음')
    # 새 캐릭터 만들기: 첫 화면의 1회 보정이 서버 값을 바꾸지 않아야 함
    g("window.__CT.push({kind:'monster',id:'tracker',data:{kind:'party',name:'추적자',hp:5555,atk:70,level:15,min:3,max:4,target:3,roles:{tank:1,dps:1,heal:1}},published:true,starts_at:null,ends_at:null,rev:2,sort:0});window.__CT_CB({})")
    pg.wait_for_timeout(1300)
    pg.fill('input[maxlength="10"]','테스터');pg.locator('form button[type=submit], .create button.btn-primary').first.click();pg.wait_for_timeout(800)
    ok(g("!!S.me"),'캐릭터 생성됨')
    ok(g("monster('tracker').hp")==5555,'캐릭터 생성 후에도 서버 값 유지 (hp 5555)')
    pg.evaluate("ctRefresh()");pg.wait_for_timeout(600)
    ok(g("monster('tracker').hp")==5555,'다시 받아도 그대로')
    ok(not errs,'콘솔 오류 없음 '+'; '.join(errs[:3]))
    pg.screenshot(path=OUT+'/g1.png')
    b.close()
print('\n'.join(res));print('PASS',sum(r.startswith('OK') for r in res),'/',len(res))
